//! Lowering the typed IR to WGSL. The output is a pure function of the program: no maps
//! with random iteration order, helpers in a fixed order, so the same kernel always gives
//! byte-identical text.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::ops::Range;

use crate::Target;
use crate::bindings::{
    Access, AttrBinding, Bindings, ImageBinding, PARAMS_OFFSET, ParamType, Slot, WORKGROUP_SIZE,
};
use crate::diag::{Error, Span};
use crate::ir::*;
use crate::stdlib::{self, Lib};
use crate::types::{Scalar, Type};

/// Maps ranges of the generated WGSL back to the kernel source.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SourceMap {
    /// (byte range in the WGSL, span in the kernel), in emission order.
    pub entries: Vec<(Range<usize>, Span)>,
}

impl SourceMap {
    /// The kernel span of the smallest mapped WGSL range containing `offset`.
    pub fn kernel_span(&self, offset: usize) -> Option<Span> {
        self.entries
            .iter()
            .filter(|(r, _)| r.start <= offset && offset < r.end.max(r.start + 1))
            .min_by_key(|(r, _)| r.end - r.start)
            .map(|(_, s)| *s)
    }

    /// The kernel span of the first statement emitted on WGSL line `line` (1-based) or
    /// the closest one before it.
    pub fn kernel_span_for_line(&self, wgsl: &str, line: usize) -> Option<Span> {
        let start: usize = wgsl
            .split_inclusive('\n')
            .take(line.saturating_sub(1))
            .map(str::len)
            .sum();
        self.kernel_span(start).or_else(|| {
            self.entries
                .iter()
                .filter(|(r, _)| r.start <= start)
                .max_by_key(|(r, _)| r.start)
                .map(|(_, s)| *s)
        })
    }
}

pub(crate) struct Lowered {
    pub wgsl: String,
    pub bindings: Bindings,
    pub source_map: SourceMap,
}

/// One attribute's resources.
#[derive(Debug)]
struct AttrRes {
    /// Storage buffer read and written at this element.
    buffer: String,
    /// Buffer holding the input values for other elements (`point()`).
    other: String,
    /// The per-invocation copy the kernel works on.
    private: String,
}

pub(crate) fn lower(p: &Program, max_storage_buffers: u32) -> Result<Lowered, Error> {
    let mut l = Lowerer {
        p,
        out: String::new(),
        map: Vec::new(),
        lib: BTreeSet::new(),
        indent: 0,
        next_loop: 0,
        locals: &[],
        res: Vec::new(),
    };
    let bindings = l.bindings(max_storage_buffers)?;

    // Bodies first (they decide which helpers are used), then the prelude in front.
    let mut body = String::new();
    std::mem::swap(&mut l.out, &mut body);
    for f in &p.functions {
        l.function(f);
    }
    l.kernel_fn();
    l.entry_points();
    std::mem::swap(&mut l.out, &mut body);

    let mut head = String::new();
    head.push_str(&format!(
        "// Generated by atd-kernel from a {} kernel. Do not edit: edit the kernel.\n",
        match p.target {
            Target::Points => "Points",
            Target::Pixels => "Pixels",
        }
    ));
    l.prelude(&mut head, &bindings);
    head.push_str(&stdlib::emit(&l.lib));
    head.push_str(&l.generated_helpers());
    head.push('\n');

    let shift = head.len();
    let entries = l
        .map
        .into_iter()
        .map(|(r, s)| (r.start + shift..r.end + shift, s))
        .collect();
    head.push_str(&body);
    Ok(Lowered {
        wgsl: head,
        bindings,
        source_map: SourceMap { entries },
    })
}

struct Lowerer<'p> {
    p: &'p Program,
    out: String,
    map: Vec<(Range<usize>, Span)>,
    lib: BTreeSet<Lib>,
    indent: usize,
    next_loop: u32,
    /// Locals of the function being emitted.
    locals: &'p [Local],
    /// Per attribute (by `AttrId`).
    res: Vec<AttrRes>,
}

fn float_lit(v: f32) -> String {
    if !v.is_finite() {
        return "0.0f".into();
    }
    let s = format!("{v:?}");
    if v.is_sign_negative() {
        format!("({s}f)")
    } else {
        format!("{s}f")
    }
}

fn int_lit(v: i32) -> String {
    if v == i32::MIN {
        "(-2147483647i - 1i)".into()
    } else if v < 0 {
        format!("({v}i)")
    } else {
        format!("{v}i")
    }
}

const XYZW: [char; 4] = ['x', 'y', 'z', 'w'];

impl<'p> Lowerer<'p> {
    // ---- layout ----------------------------------------------------------------------

    fn bindings(&mut self, max_storage: u32) -> Result<Bindings, Error> {
        let p = self.p;
        let mut images: Vec<u32> = p.images.clone();
        if p.target == Target::Pixels && !images.contains(&0) {
            images.insert(0, 0);
        }
        let (image_group, uniforms, header, sampler) = match p.target {
            Target::Points => (
                2,
                Slot {
                    group: 0,
                    binding: 1,
                    wgsl_name: "atd_u".into(),
                },
                Some(Slot {
                    group: 0,
                    binding: 0,
                    wgsl_name: "atd_header".into(),
                }),
                (!images.is_empty()).then(|| Slot {
                    group: 0,
                    binding: 2,
                    wgsl_name: "atd_samp".into(),
                }),
            ),
            Target::Pixels => (
                1,
                Slot {
                    group: 0,
                    binding: 0,
                    wgsl_name: "atd_u".into(),
                },
                None,
                Some(Slot {
                    group: 0,
                    binding: 1,
                    wgsl_name: "atd_samp".into(),
                }),
            ),
        };

        // Attributes sorted by name (stable across edits that reorder the code).
        let mut order: Vec<usize> = (0..p.attrs.len()).collect();
        order.sort_by(|a, b| p.attrs[*a].name.cmp(&p.attrs[*b].name));
        self.res = p
            .attrs
            .iter()
            .map(|a| AttrRes {
                buffer: format!("attr_{}", a.name),
                other: if a.written && a.read_other {
                    format!("in_{}", a.name)
                } else {
                    format!("attr_{}", a.name)
                },
                private: format!("a_{}", a.name),
            })
            .collect();
        let mut attributes = Vec::new();
        if p.target == Target::Points {
            for &i in &order {
                let a = &p.attrs[i];
                let mk = |name: String, access, snapshot| AttrBinding {
                    name: a.name.clone(),
                    ty: a.storage,
                    kernel_type: a.ty,
                    access,
                    snapshot,
                    created_if_missing: a.written,
                    group: 1,
                    binding: 0,
                    stride: a.storage.stride(),
                    wgsl_name: name,
                };
                let access = if a.written {
                    Access::ReadWrite
                } else {
                    Access::Read
                };
                attributes.push(mk(format!("attr_{}", a.name), access, false));
                if a.written && a.read_other {
                    attributes.push(mk(format!("in_{}", a.name), Access::Read, true));
                }
            }
            for (k, b) in attributes.iter_mut().enumerate() {
                b.binding = k as u32;
            }
        }
        let bindings = Bindings {
            target: p.target,
            workgroup_size: if p.target == Target::Points {
                WORKGROUP_SIZE
            } else {
                0
            },
            entry_point: match p.target {
                Target::Points => "main".into(),
                Target::Pixels => "fs".into(),
            },
            vertex_entry_point: (p.target == Target::Pixels).then(|| "vs".into()),
            header,
            uniforms,
            uniform_size: PARAMS_OFFSET + 16 * p.params.len().max(1) as u64,
            sampler,
            attributes,
            images: images
                .iter()
                .map(|&i| ImageBinding {
                    input: i,
                    group: image_group,
                    binding: i,
                    wgsl_name: format!("atd_img{i}"),
                })
                .collect(),
        };
        if bindings.storage_buffers() > max_storage {
            return Err(Error::new(
                p.attrs.first().map_or(Span::default(), |a| a.span),
                format!(
                    "this kernel binds {} storage buffers; devices guarantee {max_storage}",
                    bindings.storage_buffers()
                ),
            )
            .hint("use fewer attributes in one kernel, or split it in two"));
        }
        Ok(bindings)
    }

    fn prelude(&self, out: &mut String, b: &Bindings) {
        let p = self.p;
        let n = p.params.len().max(1);
        out.push_str("\nstruct AtdUniforms {\n    // time, time step, frame, 0\n    globals: vec4f,\n    // width, height, 1 / width, 1 / height (pixels)\n    res: vec4f,\n");
        let _ = writeln!(out, "    p: array<vec4f, {n}>,\n}}\n");
        if !p.params.is_empty() {
            out.push_str("// Parameters:\n");
            for prm in &p.params {
                let _ = writeln!(
                    out,
                    "//   p[{}] {} = ch(\"{}\")",
                    prm.slot,
                    prm.ty.kernel_type(),
                    prm.name
                );
            }
            out.push('\n');
        }
        if let Some(h) = &b.header {
            out.push_str("struct AtdHeader {\n    count: u32,\n    capacity: u32,\n}\n\n");
            let _ = writeln!(
                out,
                "@group({}) @binding({}) var<storage, read> {}: AtdHeader;",
                h.group, h.binding, h.wgsl_name
            );
        }
        let _ = writeln!(
            out,
            "@group({}) @binding({}) var<uniform> {}: AtdUniforms;",
            b.uniforms.group, b.uniforms.binding, b.uniforms.wgsl_name
        );
        if let Some(s) = &b.sampler {
            let _ = writeln!(
                out,
                "@group({}) @binding({}) var {}: sampler;",
                s.group, s.binding, s.wgsl_name
            );
        }
        for a in &b.attributes {
            let access = match a.access {
                Access::Read => "read",
                Access::ReadWrite => "read_write",
            };
            let what = if a.snapshot {
                format!("input values of @{} for point()", a.name)
            } else {
                format!("@{}: {} ({})", a.name, a.kernel_type, a.ty)
            };
            let _ = writeln!(
                out,
                "@group({}) @binding({}) var<storage, {access}> {}: array<{}>; // {what}",
                a.group,
                a.binding,
                a.wgsl_name,
                a.ty.wgsl()
            );
        }
        for i in &b.images {
            let _ = writeln!(
                out,
                "@group({}) @binding({}) var {}: texture_2d<f32>; // input image {}",
                i.group, i.binding, i.wgsl_name, i.input
            );
        }
        out.push('\n');
        match p.target {
            Target::Points => {
                out.push_str("var<private> atd_index: u32;\n");
                let mut order: Vec<usize> = (0..p.attrs.len()).collect();
                order.sort_by(|a, b| p.attrs[*a].name.cmp(&p.attrs[*b].name));
                for i in order {
                    let _ = writeln!(
                        out,
                        "var<private> {}: {};",
                        self.res[i].private,
                        p.attrs[i].ty.wgsl()
                    );
                }
            }
            Target::Pixels => {
                out.push_str("var<private> atd_ix: i32;\nvar<private> atd_iy: i32;\nvar<private> atd_uv: vec2f;\nvar<private> a_Cd: vec4f;\n");
            }
        }
    }

    /// Per-attribute `point()` readers and `nearpoint()`.
    fn generated_helpers(&self) -> String {
        let p = self.p;
        let mut out = String::new();
        let mut order: Vec<usize> = (0..p.attrs.len()).collect();
        order.sort_by(|a, b| p.attrs[*a].name.cmp(&p.attrs[*b].name));
        let uses_point = |id: usize| {
            uses(
                p,
                &|e| matches!(e.kind, ExprKind::PointRead(a, _) if a as usize == id),
            )
        };
        for i in order {
            let a = &p.attrs[i];
            if !a.read_other || !uses_point(i) {
                continue;
            }
            let t = a.ty.wgsl();
            let read = load(&format!("{}[u32(i)]", self.res[i].other), a.storage.scalar);
            let _ = write!(
                out,
                "\nfn atd_point_{}(i: i32) -> {t} {{\n    if (i < 0i || u32(i) >= atd_header.count) {{\n        return {t}();\n    }}\n    return {read};\n}}\n",
                a.name
            );
        }
        if uses(p, &|e| matches!(e.kind, ExprKind::NearPoint(..))) {
            let pos = self.position_buffer();
            let _ = write!(
                out,
                "\n// The closest point to `pos` (lowest index on ties), or -1; maxdist < 0: no limit.\nfn atd_nearpoint(pos: vec3f, maxdist: f32) -> i32 {{\n    var best = -1i;\n    var best_d2 = 0.0f;\n    for (var k = 0u; k < atd_header.count; k++) {{\n        let d = {pos}[k] - pos;\n        let d2 = dot(d, d);\n        if (maxdist >= 0.0f && d2 > maxdist * maxdist) {{\n            continue;\n        }}\n        if (best < 0i || d2 < best_d2) {{\n            best = i32(k);\n            best_d2 = d2;\n        }}\n    }}\n    return best;\n}}\n"
            );
        }
        out
    }

    fn position_buffer(&self) -> String {
        self.p
            .attrs
            .iter()
            .position(|a| a.name == "P")
            .map_or_else(|| "attr_P".into(), |i| self.res[i].other.clone())
    }

    // ---- functions -------------------------------------------------------------------

    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn start_line(&mut self) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
    }

    fn local(&self, id: LocalId) -> String {
        let name = self
            .locals
            .get(id as usize)
            .map_or("x", |l| l.name.as_str());
        format!("l{id}_{name}")
    }

    fn function(&mut self, f: &'p Function) {
        self.locals = &f.locals;
        let params: Vec<String> = f
            .params
            .iter()
            .map(|&id| {
                let l = &f.locals[id as usize];
                format!("p_{}: {}", l.name, l.ty.wgsl())
            })
            .collect();
        let ret = if f.ret == Type::Void {
            String::new()
        } else {
            format!(" -> {}", f.ret.wgsl())
        };
        self.out.push('\n');
        let sig = format!("fn u_{}({}){ret} {{", f.name, params.join(", "));
        self.line(&sig);
        self.indent += 1;
        for &id in &f.params {
            let l = &f.locals[id as usize];
            let text = format!("var {}: {} = p_{};", self.local(id), l.ty.wgsl(), l.name);
            self.line(&text);
        }
        self.stmts(&f.body);
        self.indent -= 1;
        self.line("}");
    }

    fn kernel_fn(&mut self) {
        let f = &self.p.body;
        self.locals = &f.locals;
        self.out.push('\n');
        self.line("fn atd_kernel() {");
        self.indent += 1;
        self.stmts(&f.body);
        self.indent -= 1;
        self.line("}");
    }

    fn entry_points(&mut self) {
        let p = self.p;
        match p.target {
            Target::Points => {
                let _ = write!(
                    self.out,
                    "\n@compute @workgroup_size({WORKGROUP_SIZE})\nfn main(@builtin(global_invocation_id) atd_gid: vec3u, @builtin(num_workgroups) atd_nwg: vec3u) {{\n    atd_index = atd_gid.x + atd_gid.y * atd_nwg.x * {WORKGROUP_SIZE}u;\n    if (atd_index >= atd_header.count) {{\n        return;\n    }}\n"
                );
                let mut order: Vec<usize> = (0..p.attrs.len()).collect();
                order.sort_by(|a, b| p.attrs[*a].name.cmp(&p.attrs[*b].name));
                for &i in &order {
                    let a = &p.attrs[i];
                    if a.read || a.written {
                        let r = &self.res[i];
                        let v = load(&format!("{}[atd_index]", r.buffer), a.storage.scalar);
                        let _ = writeln!(self.out, "    {} = {v};", r.private);
                    }
                }
                self.out.push_str("    atd_kernel();\n");
                for &i in &order {
                    let a = &p.attrs[i];
                    if a.written {
                        let r = &self.res[i];
                        let v = store(&r.private, a.storage.scalar);
                        let _ = writeln!(self.out, "    {}[atd_index] = {v};", r.buffer);
                    }
                }
                self.out.push_str("}\n");
            }
            Target::Pixels => {
                self.out.push_str(
                    "\nstruct AtdVsOut {\n    @builtin(position) pos: vec4f,\n}\n\n// One triangle covering the output.\n@vertex\nfn vs(@builtin(vertex_index) i: u32) -> AtdVsOut {\n    let p = vec2f(f32((i << 1u) & 2u), f32(i & 2u));\n    var out: AtdVsOut;\n    out.pos = vec4f(p * vec2f(2.0f, -2.0f) + vec2f(-1.0f, 1.0f), 0.0f, 1.0f);\n    return out;\n}\n\n@fragment\nfn fs(v: AtdVsOut) -> @location(0) vec4f {\n    atd_ix = i32(floor(v.pos.x));\n    atd_iy = i32(floor(v.pos.y));\n    atd_uv = v.pos.xy * atd_u.res.zw;\n    a_Cd = textureSampleLevel(atd_img0, atd_samp, atd_uv, 0.0f);\n    atd_kernel();\n    return a_Cd;\n}\n",
                );
            }
        }
    }

    // ---- statements ------------------------------------------------------------------

    fn stmts(&mut self, stmts: &[Stmt]) {
        for s in stmts {
            self.stmt(s);
        }
    }

    fn mapped(&mut self, span: Span, f: impl FnOnce(&mut Self)) {
        let start = self.out.len();
        f(self);
        let end = self.out.len();
        if span != Span::default() {
            self.map.push((start..end, span));
        }
    }

    fn stmt(&mut self, s: &Stmt) {
        let span = s.span;
        match &s.kind {
            StmtKind::Decl(id, init) => {
                let ty = self.locals.get(*id as usize).map_or(Type::Float, |l| l.ty);
                self.start_line();
                self.mapped(span, |w| {
                    let _ = write!(w.out, "var {}: {}", w.local(*id), ty.wgsl());
                    if let Some(v) = init {
                        w.out.push_str(" = ");
                        w.expr(v);
                    }
                    w.out.push(';');
                });
                self.out.push('\n');
            }
            StmtKind::Assign(place, v) if matches!(place.comp, Some(Comp::Dynamic(_))) => {
                // `v[i] = x` with a variable `i` is not a valid l-value for FXC
                // (Direct3D, so Windows on WARP): "array reference cannot be
                // used as an l-value". Write through constant indices instead,
                // selected by the clamped index, the same behaviour as a read.
                let Some(Comp::Dynamic(i)) = &place.comp else {
                    return;
                };
                let base = match place.base {
                    PlaceBase::Local(id) => self.local(id),
                    PlaceBase::Attr(id) => self.res[id as usize].private.clone(),
                };
                let base_ty = match place.base {
                    PlaceBase::Local(id) => self.locals.get(id as usize).map(|l| l.ty),
                    PlaceBase::Attr(id) => self.p.attrs.get(id as usize).map(|a| a.ty),
                }
                .unwrap_or(Type::Vec(4));
                let (n, value_ty, is_vec) = match base_ty {
                    Type::Mat(n) => (n, format!("vec{n}f"), false),
                    Type::Vec(n) => (n, "f32".to_owned(), true),
                    _ => (1, "f32".to_owned(), true),
                };
                self.line("{");
                self.indent += 1;
                self.start_line();
                self.mapped(span, |w| {
                    w.out.push_str("let atd_di: i32 = clamp(");
                    w.expr(i);
                    let _ = write!(w.out, ", 0i, {}i);", n.max(1) - 1);
                });
                self.out.push('\n');
                self.start_line();
                self.mapped(span, |w| {
                    let _ = write!(w.out, "let atd_dv: {value_ty} = ");
                    w.expr(v);
                    w.out.push(';');
                });
                self.out.push('\n');
                for k in 0..n.max(1) {
                    let target = if is_vec {
                        format!("{base}.{}", XYZW[usize::from(k).min(3)])
                    } else {
                        format!("{base}[{k}]")
                    };
                    let head = if k == 0 { "if" } else { "} else if" };
                    let last = k + 1 == n.max(1);
                    let cond = if last {
                        "} else {".to_owned()
                    } else {
                        format!("{head} (atd_di == {k}i) {{")
                    };
                    self.line(&cond);
                    self.indent += 1;
                    self.line(&format!("{target} = atd_dv;"));
                    self.indent -= 1;
                }
                self.line("}");
                self.indent -= 1;
                self.line("}");
            }
            StmtKind::Assign(place, v) => {
                self.start_line();
                self.mapped(span, |w| {
                    let base = match place.base {
                        PlaceBase::Local(id) => w.local(id),
                        PlaceBase::Attr(id) => w.res[id as usize].private.clone(),
                    };
                    w.out.push_str(&base);
                    let base_ty = match place.base {
                        PlaceBase::Local(id) => w.locals.get(id as usize).map(|l| l.ty),
                        PlaceBase::Attr(id) => w.p.attrs.get(id as usize).map(|a| a.ty),
                    }
                    .unwrap_or(Type::Vec(4));
                    let n = match base_ty {
                        Type::Mat(n) | Type::Vec(n) => n,
                        _ => 1,
                    };
                    match &place.comp {
                        None => {}
                        Some(Comp::Const(k)) if matches!(base_ty, Type::Vec(_)) => {
                            w.out.push('.');
                            w.out.push(XYZW[usize::from(*k).min(3)]);
                        }
                        Some(Comp::Const(k)) => {
                            let _ = write!(w.out, "[{k}]");
                        }
                        Some(Comp::Dynamic(i)) => {
                            w.out.push_str("[clamp(");
                            w.expr(i);
                            let _ = write!(w.out, ", 0i, {}i)]", n.max(1) - 1);
                        }
                    }
                    w.out.push_str(" = ");
                    w.expr(v);
                    w.out.push(';');
                });
                self.out.push('\n');
            }
            StmtKind::If(c, t, e) => {
                self.start_line();
                self.mapped(span, |w| {
                    w.out.push_str("if (");
                    w.expr(c);
                    w.out.push_str(") {");
                });
                self.out.push('\n');
                self.indent += 1;
                self.stmts(t);
                self.indent -= 1;
                if e.is_empty() {
                    self.line("}");
                } else {
                    self.line("} else {");
                    self.indent += 1;
                    self.stmts(e);
                    self.indent -= 1;
                    self.line("}");
                }
            }
            StmtKind::For {
                var,
                start,
                end,
                cmp,
                step,
                body,
            } => {
                let k = self.next_loop;
                self.next_loop += 1;
                let v = self.local(*var);
                self.line("{");
                self.indent += 1;
                self.start_line();
                self.mapped(start.span, |w| {
                    let _ = write!(w.out, "var {v}: i32 = ");
                    w.expr(start);
                    w.out.push(';');
                });
                self.out.push('\n');
                self.start_line();
                self.mapped(end.span, |w| {
                    let _ = write!(w.out, "let atd_end{k}: i32 = ");
                    w.expr(end);
                    w.out.push(';');
                });
                self.out.push('\n');
                self.line(&format!("var atd_trip{k}: u32 = 0u;"));
                self.start_line();
                self.mapped(span, |w| w.out.push_str("loop {"));
                self.out.push('\n');
                self.indent += 1;
                let op = match cmp {
                    Cmp::Lt => "<",
                    Cmp::Le => "<=",
                    Cmp::Gt => ">",
                    Cmp::Ge => ">=",
                };
                self.line(&format!("if (!({v} {op} atd_end{k})) {{"));
                self.line("    break;");
                self.line("}");
                self.stmts(body);
                self.line("continuing {");
                self.line(&format!("    {v} = {v} + {};", int_lit(*step)));
                self.line(&format!("    atd_trip{k} = atd_trip{k} + 1u;"));
                self.line(&format!("    break if atd_trip{k} >= {MAX_TRIP}u;"));
                self.line("}");
                self.indent -= 1;
                self.line("}");
                self.indent -= 1;
                self.line("}");
            }
            StmtKind::NearPoints {
                var,
                pos,
                radius,
                max,
                body,
            } => {
                let k = self.next_loop;
                self.next_loop += 1;
                let v = self.local(*var);
                let src = self.position_buffer();
                self.line("{");
                self.indent += 1;
                for (name, e, ty) in [
                    ("pos", pos, "vec3f"),
                    ("r", radius, "f32"),
                    ("max", max, "i32"),
                ] {
                    self.start_line();
                    self.mapped(e.span, |w| {
                        let _ = write!(w.out, "let atd_np_{name}{k}: {ty} = ");
                        w.expr(e);
                        w.out.push(';');
                    });
                    self.out.push('\n');
                }
                self.line(&format!("var atd_np_found{k}: i32 = 0i;"));
                self.start_line();
                self.mapped(span, |w| {
                    let _ = write!(
                        w.out,
                        "for (var atd_np_k{k}: u32 = 0u; atd_np_k{k} < atd_header.count; atd_np_k{k}++) {{"
                    );
                });
                self.out.push('\n');
                self.indent += 1;
                self.line(&format!("if (atd_np_found{k} >= atd_np_max{k}) {{"));
                self.line("    break;");
                self.line("}");
                self.line(&format!(
                    "let atd_np_d{k} = {src}[atd_np_k{k}] - atd_np_pos{k};"
                ));
                self.line(&format!(
                    "if (dot(atd_np_d{k}, atd_np_d{k}) > atd_np_r{k} * atd_np_r{k}) {{"
                ));
                self.line("    continue;");
                self.line("}");
                self.line(&format!("atd_np_found{k} = atd_np_found{k} + 1i;"));
                self.line(&format!("var {v}: i32 = i32(atd_np_k{k});"));
                self.stmts(body);
                self.indent -= 1;
                self.line("}");
                self.indent -= 1;
                self.line("}");
            }
            StmtKind::Break => self.simple(span, "break;"),
            StmtKind::Continue => self.simple(span, "continue;"),
            StmtKind::Return(None) => self.simple(span, "return;"),
            StmtKind::Return(Some(v)) => {
                self.start_line();
                self.mapped(span, |w| {
                    w.out.push_str("return ");
                    w.expr(v);
                    w.out.push(';');
                });
                self.out.push('\n');
            }
            StmtKind::Expr(e) => {
                self.start_line();
                self.mapped(span, |w| {
                    if e.ty != Type::Void {
                        w.out.push_str("_ = ");
                    }
                    w.expr(e);
                    w.out.push(';');
                });
                self.out.push('\n');
            }
            StmtKind::Block(b) => {
                self.line("{");
                self.indent += 1;
                self.stmts(b);
                self.indent -= 1;
                self.line("}");
            }
        }
    }

    fn simple(&mut self, span: Span, text: &str) {
        self.start_line();
        self.mapped(span, |w| w.out.push_str(text));
        self.out.push('\n');
    }

    // ---- expressions -----------------------------------------------------------------

    fn args(&mut self, args: &[Expr]) {
        for (i, a) in args.iter().enumerate() {
            if i > 0 {
                self.out.push_str(", ");
            }
            self.expr(a);
        }
    }

    fn call(&mut self, name: &str, args: &[Expr]) {
        self.out.push_str(name);
        self.out.push('(');
        self.args(args);
        self.out.push(')');
    }

    fn use_lib(&mut self, lib: Lib) -> String {
        self.lib.insert(lib);
        lib.name()
    }

    fn expr(&mut self, e: &Expr) {
        let span = e.span;
        self.mapped(span, |w| w.expr_inner(e));
    }

    fn expr_inner(&mut self, e: &Expr) {
        match &e.kind {
            ExprKind::Bool(b) => self.out.push_str(if *b { "true" } else { "false" }),
            ExprKind::Int(v) => self.out.push_str(&int_lit(*v)),
            ExprKind::Float(v) => self.out.push_str(&float_lit(*v)),
            ExprKind::Local(id) => {
                let n = self.local(*id);
                self.out.push_str(&n);
            }
            ExprKind::Attr(id) => {
                let n = self.res[*id as usize].private.clone();
                self.out.push_str(&n);
            }
            ExprKind::Global(g) => self.out.push_str(match g {
                Global::PtNum => "i32(atd_index)",
                Global::NumPt => "i32(atd_header.count)",
                Global::Time => "atd_u.globals.x",
                Global::TimeInc => "atd_u.globals.y",
                Global::Frame => "atd_u.globals.z",
                Global::Ix => "atd_ix",
                Global::Iy => "atd_iy",
                Global::PixelP => "atd_uv",
                Global::Res => "atd_u.res.xy",
            }),
            ExprKind::Param(slot) => {
                let ty = self
                    .p
                    .params
                    .iter()
                    .find(|p| p.slot == *slot)
                    .map_or(ParamType::Float, |p| p.ty);
                let _ = match ty {
                    ParamType::Float => write!(self.out, "atd_u.p[{slot}].x"),
                    ParamType::Int => write!(self.out, "bitcast<i32>(atd_u.p[{slot}].x)"),
                    ParamType::Vec2 => write!(self.out, "atd_u.p[{slot}].xy"),
                    ParamType::Vec3 => write!(self.out, "atd_u.p[{slot}].xyz"),
                    ParamType::Vec4 => write!(self.out, "atd_u.p[{slot}]"),
                };
            }
            ExprKind::Unary(op, v) => {
                self.out.push_str(match op {
                    UnOp::Neg => "(-",
                    UnOp::Not => "(!",
                    UnOp::BitNot => "(~",
                });
                self.expr(v);
                self.out.push(')');
            }
            ExprKind::Binary(op, l, r) => self.binary(*op, l, r),
            ExprKind::Select(c, a, b) => {
                self.out.push_str("select(");
                self.expr(b);
                self.out.push_str(", ");
                self.expr(a);
                self.out.push_str(", ");
                self.expr(c);
                self.out.push(')');
            }
            ExprKind::Convert(v) | ExprKind::Splat(v) => {
                self.out.push_str(e.ty.wgsl());
                self.out.push('(');
                self.expr(v);
                self.out.push(')');
            }
            ExprKind::Construct(args) => self.call(e.ty.wgsl(), args),
            ExprKind::Swizzle(v, idx) => {
                self.out.push('(');
                self.expr(v);
                self.out.push_str(").");
                for &i in idx {
                    self.out.push(XYZW[usize::from(i).min(3)]);
                }
            }
            ExprKind::Index(v, i) => match v.ty {
                Type::Mat(n) => {
                    let f = self.use_lib(Lib::Col(n));
                    self.call(&f, &[(**v).clone(), (**i).clone()]);
                }
                ty => {
                    self.out.push('(');
                    self.expr(v);
                    self.out.push_str(")[clamp(");
                    self.expr(i);
                    let _ = write!(self.out, ", 0i, {}i)]", ty.components().max(1) - 1);
                }
            },
            ExprKind::Builtin(b, args) => self.builtin(*b, args, e.ty),
            ExprKind::Call(id, args) => {
                let name = self
                    .p
                    .functions
                    .get(*id as usize)
                    .map_or("missing", |f| f.name.as_str());
                self.call(&format!("u_{name}"), args);
            }
            ExprKind::PointRead(id, i) => {
                let name = self.p.attrs[*id as usize].name.clone();
                self.call(&format!("atd_point_{name}"), std::slice::from_ref(i));
            }
            ExprKind::NumPoints => self.out.push_str("i32(atd_header.count)"),
            ExprKind::NearPoint(pos, maxd) => {
                self.out.push_str("atd_nearpoint(");
                self.expr(pos);
                self.out.push_str(", ");
                match maxd {
                    Some(d) => self.expr(d),
                    None => self.out.push_str("-1.0f"),
                }
                self.out.push(')');
            }
            ExprKind::Texture(n, uv) => {
                let _ = write!(self.out, "textureSampleLevel(atd_img{n}, atd_samp, ");
                self.expr(uv);
                self.out.push_str(", 0.0f)");
            }
        }
    }

    fn binary(&mut self, op: BinOp, l: &Expr, r: &Expr) {
        let int = l.ty == Type::Int;
        match op {
            BinOp::Div if int => {
                let f = self.use_lib(Lib::Idiv);
                self.call(&f, &[l.clone(), r.clone()]);
            }
            BinOp::Rem if int => {
                let f = self.use_lib(Lib::Imod);
                self.call(&f, &[l.clone(), r.clone()]);
            }
            BinOp::Eq | BinOp::Ne if matches!(l.ty, Type::Vec(_)) => {
                self.out
                    .push_str(if op == BinOp::Eq { "all(" } else { "any(" });
                self.expr(l);
                self.out
                    .push_str(if op == BinOp::Eq { " == " } else { " != " });
                self.expr(r);
                self.out.push(')');
            }
            BinOp::Shl | BinOp::Shr => {
                self.out.push('(');
                self.expr(l);
                self.out.push_str(if op == BinOp::Shl {
                    " << (u32("
                } else {
                    " >> (u32("
                });
                self.expr(r);
                self.out.push_str(") & 31u))");
            }
            _ => {
                self.out.push('(');
                self.expr(l);
                self.out.push(' ');
                self.out.push_str(op.symbol());
                self.out.push(' ');
                self.expr(r);
                self.out.push(')');
            }
        }
    }

    fn builtin(&mut self, b: Builtin, args: &[Expr], ty: Type) {
        use Builtin as B;
        let arg_ty = args.first().map_or(Type::Float, |a| a.ty);
        let direct = match b {
            B::Abs => Some("abs"),
            B::Sign => Some("sign"),
            B::Floor => Some("floor"),
            B::Ceil => Some("ceil"),
            B::Fract => Some("fract"),
            B::Trunc => Some("trunc"),
            B::Round => Some("round"),
            B::Sqrt => Some("sqrt"),
            B::Exp => Some("exp"),
            B::Log => Some("log"),
            B::Log2 => Some("log2"),
            B::Sin => Some("sin"),
            B::Cos => Some("cos"),
            B::Tan => Some("tan"),
            B::Asin => Some("asin"),
            B::Acos => Some("acos"),
            B::Atan => Some("atan"),
            B::Radians => Some("radians"),
            B::Degrees => Some("degrees"),
            B::Atan2 => Some("atan2"),
            B::Pow => Some("pow"),
            B::Min => Some("min"),
            B::Max => Some("max"),
            B::Step => Some("step"),
            B::Clamp => Some("clamp"),
            B::Mix => Some("mix"),
            B::Length => Some("length"),
            B::Distance => Some("distance"),
            B::Dot => Some("dot"),
            B::Cross => Some("cross"),
            B::Transpose => Some("transpose"),
            B::Determinant => Some("determinant"),
            _ => None,
        };
        if let Some(f) = direct {
            if b == B::Clamp && ty != Type::Int {
                // WGSL clamp(x, lo, hi) is min(max(x, lo), hi) for floats too; spelled out
                // so lo > hi has the same meaning on every backend.
                self.out.push_str("min(max(");
                self.expr(&args[0]);
                self.out.push_str(", ");
                self.expr(&args[1]);
                self.out.push_str("), ");
                self.expr(&args[2]);
                self.out.push(')');
                return;
            }
            self.call(f, args);
            return;
        }
        let lib = match b {
            B::Smoothstep => Lib::Smoothstep(ty),
            B::Fit => Lib::Fit(ty),
            B::Normalize => Lib::Normalize(arg_ty),
            B::Length2 => Lib::Length2(arg_ty),
            B::Distance2 => {
                let f = self.use_lib(Lib::Length2(arg_ty));
                self.out.push_str(&f);
                self.out.push_str("((");
                self.expr(&args[0]);
                self.out.push_str(") - (");
                self.expr(&args[1]);
                self.out.push_str("))");
                return;
            }
            B::Invert => {
                if arg_ty == Type::Mat(3) {
                    Lib::Inverse3
                } else {
                    Lib::Inverse4
                }
            }
            B::Ident => {
                let n = if ty == Type::Mat(3) { 3 } else { 4 };
                let cols: Vec<String> = (0..n)
                    .map(|c| {
                        let comps: Vec<&str> = (0..n)
                            .map(|r| if r == c { "1.0f" } else { "0.0f" })
                            .collect();
                        format!("{}({})", Type::Vec(n).wgsl(), comps.join(", "))
                    })
                    .collect();
                let _ = write!(self.out, "{}({})", ty.wgsl(), cols.join(", "));
                return;
            }
            B::Quaternion => Lib::Quaternion,
            B::QMultiply => Lib::QMultiply,
            B::QRotate => Lib::QRotate,
            B::QInvert => Lib::QInvert,
            B::QConvert => Lib::QConvert,
            B::Slerp => Lib::Slerp,
            B::Perlin => {
                if arg_ty == Type::Vec(2) {
                    Lib::Perlin2
                } else {
                    Lib::Perlin3
                }
            }
            B::Simplex => {
                if arg_ty == Type::Vec(2) {
                    Lib::Simplex2
                } else {
                    Lib::Simplex3
                }
            }
            B::Worley => {
                if arg_ty == Type::Vec(2) {
                    Lib::Worley2
                } else {
                    Lib::Worley3
                }
            }
            B::CurlNoise => Lib::Curl,
            B::Rand => match arg_ty {
                Type::Int => Lib::RandI,
                Type::Float => Lib::RandF,
                Type::Vec(2) => Lib::Rand2,
                _ => Lib::Rand3,
            },
            _ => Lib::Idiv,
        };
        let f = self.use_lib(lib);
        self.call(&f, args);
    }
}

/// Reads storage as the kernel type (`u32` storage converts to `int`).
fn load(expr: &str, scalar: Scalar) -> String {
    match scalar {
        Scalar::U32 => format!("i32({expr})"),
        _ => expr.to_owned(),
    }
}

fn store(expr: &str, scalar: Scalar) -> String {
    match scalar {
        Scalar::U32 => format!("u32({expr})"),
        _ => expr.to_owned(),
    }
}

/// True if any expression in the program matches.
fn uses(p: &Program, pred: &dyn Fn(&Expr) -> bool) -> bool {
    p.functions
        .iter()
        .chain(std::iter::once(&p.body))
        .any(|f| f.body.iter().any(|s| stmt_uses(s, pred)))
}

fn stmt_uses(s: &Stmt, pred: &dyn Fn(&Expr) -> bool) -> bool {
    let e = |x: &Expr| expr_uses(x, pred);
    let all = |b: &[Stmt]| b.iter().any(|s| stmt_uses(s, pred));
    match &s.kind {
        StmtKind::Decl(_, init) => init.as_ref().is_some_and(e),
        StmtKind::Assign(p, v) => e(v) || matches!(&p.comp, Some(Comp::Dynamic(i)) if e(i)),
        StmtKind::If(c, t, f) => e(c) || all(t) || all(f),
        StmtKind::For {
            start, end, body, ..
        } => e(start) || e(end) || all(body),
        StmtKind::NearPoints {
            pos,
            radius,
            max,
            body,
            ..
        } => e(pos) || e(radius) || e(max) || all(body),
        StmtKind::Return(v) => v.as_ref().is_some_and(e),
        StmtKind::Expr(x) => e(x),
        StmtKind::Block(b) => all(b),
        StmtKind::Break | StmtKind::Continue => false,
    }
}

fn expr_uses(x: &Expr, pred: &dyn Fn(&Expr) -> bool) -> bool {
    if pred(x) {
        return true;
    }
    let e = |y: &Expr| expr_uses(y, pred);
    match &x.kind {
        ExprKind::Unary(_, a)
        | ExprKind::Convert(a)
        | ExprKind::Splat(a)
        | ExprKind::Swizzle(a, _)
        | ExprKind::PointRead(_, a)
        | ExprKind::Texture(_, a) => e(a),
        ExprKind::Binary(_, a, b) | ExprKind::Index(a, b) => e(a) || e(b),
        ExprKind::Select(a, b, c) => e(a) || e(b) || e(c),
        ExprKind::Construct(v) | ExprKind::Builtin(_, v) | ExprKind::Call(_, v) => v.iter().any(e),
        ExprKind::NearPoint(a, b) => e(a) || b.as_deref().is_some_and(e),
        _ => false,
    }
}
