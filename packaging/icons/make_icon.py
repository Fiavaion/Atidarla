"""Draws the Lasair app icon (concept P3: a prism of lit faces round a dark core) as SVG.

usage: python3 packaging/icons/make_icon.py [OUT_DIR]   (default: this folder)
Writes OUT_DIR/lasair.svg. Standard library only and deterministic: the
same bytes on every platform (crates/lsr-cli/tests/app_icon.rs checks the
committed file against it). Approved by Mark 2026-11-01 (PRD A69); the
raster sizes come from render_icons.sh.

Every face is a flat polygon with its own gradient, lit from the top left,
so the depth survives at any size without filters (sips, rsvg and the
Windows icon tools all render it the same).
"""
import math
import os
import sys

# Outer triangle, apex up.
O = [(512, 166), (134, 806), (890, 806)]


def incentre(t):
    (ax, ay), (bx, by), (cx, cy) = t
    # math.sqrt is correctly rounded everywhere (pow need not be).
    a = math.sqrt((bx - cx) ** 2 + (by - cy) ** 2)
    b = math.sqrt((ax - cx) ** 2 + (ay - cy) ** 2)
    c = math.sqrt((ax - bx) ** 2 + (ay - by) ** 2)
    s = a + b + c
    centre = ((a * ax + b * bx + c * cx) / s, (a * ay + b * by + c * cy) / s)
    area = abs((bx - ax) * (cy - ay) - (cx - ax) * (by - ay)) / 2
    return centre, 2 * area / s


def inset(t, d):
    """The triangle with every side moved d inwards (a scale about the incentre)."""
    (cx, cy), r = incentre(t)
    k = (r - d) / r
    return [(cx + (x - cx) * k, cy + (y - cy) * k) for x, y in t]


def pts(*ps):
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in ps)


def lin(id_, p1, p2, stops):
    s = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in stops)
    return (f'<linearGradient id="{id_}" gradientUnits="userSpaceOnUse" x1="{p1[0]:.1f}" y1="{p1[1]:.1f}" '
            f'x2="{p2[0]:.1f}" y2="{p2[1]:.1f}">{s}</linearGradient>')


def mid(p, q):
    return ((p[0] + q[0]) / 2, (p[1] + q[1]) / 2)


def icon():
    M = inset(O, 30)   # rim
    I = inset(O, 100)  # bevel down to the core
    (A, B, C), (Am, Bm, Cm), (Ai, Bi, Ci) = O, M, I
    d = []
    d.append(lin("tile", (0, 64), (0, 960), [(0, "#34353b"), (1, "#18181c")]))
    d.append('<radialGradient id="glow" cx="512" cy="560" r="470" gradientUnits="userSpaceOnUse">'
             '<stop offset="0" stop-color="#2fb7f0" stop-opacity="0.22"/>'
             '<stop offset="0.55" stop-color="#f39a1e" stop-opacity="0.10"/>'
             '<stop offset="1" stop-color="#f39a1e" stop-opacity="0"/></radialGradient>')
    d.append('<radialGradient id="shadow" cx="512" cy="818" r="380" gradientTransform="translate(0 818) scale(1 0.08) translate(0 -818)" '
             'gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#000" stop-opacity="0.6"/>'
             '<stop offset="1" stop-color="#000" stop-opacity="0"/></radialGradient>')
    # Rim faces: across each face, outer edge to inner edge.
    d.append(lin("rimL", mid(A, B), mid(Am, Bm), [(0, "#e8761a"), (0.35, "#ffb43c"), (1, "#ffc457")]))
    d.append(lin("rimR", mid(A, C), mid(Am, Cm), [(0, "#c2560e"), (0.4, "#f08a1f"), (1, "#fba531")]))
    d.append(lin("rimB", mid(B, C), mid(Bm, Cm), [(0, "#d9640f"), (0.5, "#ff9f22"), (1, "#ffbf45")]))
    # Bevel faces: the light falls on the left wall, the right wall is in shade.
    d.append(lin("bevL", mid(Am, Bm), mid(Ai, Bi), [(0, "#46b8f5"), (1, "#1676cf")]))
    d.append(lin("bevR", mid(Am, Cm), mid(Ai, Ci), [(0, "#1aa6e6"), (1, "#22d0f5")]))
    d.append(lin("bevB", mid(Bi, Ci), mid(Bm, Cm), [(0, "#18d8ee"), (0.4, "#1fc9d8"), (0.62, "#d9ec2a"), (0.85, "#b39a12"), (1, "#3c3410")]))
    d.append(lin("core", (0, Ai[1]), (0, Bi[1]), [(0, "#5c5650"), (0.55, "#24221f"), (1, "#0b0b0c")]))
    d.append(lin("fall", (0, Am[1]), (0, Bi[1]), [(0, "#ffffff"), (1, "#000000")]))
    d.append('<radialGradient id="apex" cx="%.1f" cy="%.1f" r="70" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#fff2d8" stop-opacity="0.9"/><stop offset="1" stop-color="#fff2d8" stop-opacity="0"/></radialGradient>' % (A[0], A[1] + 18))
    d.append('<radialGradient id="baseglow" cx="512" cy="%.1f" r="300" gradientTransform="translate(0 %.1f) scale(1 0.12) translate(0 -%.1f)" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#f6ff6a" stop-opacity="0.35"/><stop offset="1" stop-color="#f6ff6a" stop-opacity="0"/></radialGradient>' % ((Bi[1]+Bm[1])/2+6, (Bi[1]+Bm[1])/2+6, (Bi[1]+Bm[1])/2+6))
    d.append(lin("sheen", A, mid(B, C), [(0, "#ffffff"), (0.25, "#ffffff00"), (1, "#ffffff00")]))

    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">',
           "<!-- Lasair app icon (concept P3). Generated by make_icon.py. -->",
           "<defs>" + "".join(d) + "</defs>",
           '<rect x="64" y="64" width="896" height="896" rx="200" fill="url(#tile)"/>',
           '<rect x="64" y="64" width="896" height="896" rx="200" fill="url(#glow)"/>',
           '<rect x="110" y="788" width="804" height="60" fill="url(#shadow)"/>']
    out.append(f'<polygon points="{pts(A, B, C)}" fill="none" stroke="#e9791a" stroke-width="16" stroke-linejoin="round"/>')
    faces = [
        ("rimL", (A, B, Bm, Am)), ("rimR", (C, A, Am, Cm)), ("rimB", (B, C, Cm, Bm)),
        ("bevL", (Am, Bm, Bi, Ai)), ("bevR", (Cm, Am, Ai, Ci)), ("bevB", (Bm, Cm, Ci, Bi)),
    ]
    for g, poly in faces:
        out.append(f'<polygon points="{pts(*poly)}" fill="url(#{g})" stroke="url(#{g})" stroke-width="0.8" stroke-linejoin="round"/>')
    for poly in ((Am, Bm, Bi, Ai), (Cm, Am, Ai, Ci)):
        out.append(f'<polygon points="{pts(*poly)}" fill="url(#fall)" opacity="0.16"/>')
    out.append(f'<polygon points="{pts(Bm, Cm, Ci, Bi)}" fill="url(#baseglow)"/>')
    out.append(f'<polygon points="{pts(Ai, Bi, Ci)}" fill="url(#core)"/>')
    # Mitre lines where faces meet, and the rim's top edge catching the light.
    for p, q in ((Am, Ai), (Bm, Bi), (Cm, Ci)):
        out.append(f'<line x1="{p[0]:.1f}" y1="{p[1]:.1f}" x2="{q[0]:.1f}" y2="{q[1]:.1f}" stroke="#0b1a2a" stroke-opacity="0.35" stroke-width="3"/>')
    out.append(f'<polyline points="{pts(B, A, C)}" fill="none" stroke="url(#sheen)" stroke-opacity="0.7" stroke-width="4" stroke-linejoin="round"/>')
    out.append("</svg>")
    return "\n".join(out)


if __name__ == "__main__":
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    # newline="\n": LF on Windows too, so the bytes match the committed file.
    with open(os.path.join(out_dir, "lasair.svg"), "w", encoding="utf-8", newline="\n") as f:
        f.write(icon())
